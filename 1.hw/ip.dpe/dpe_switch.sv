// Description:
//   DPE switch: the egress IP lookup (ip.lkup) picks each packet's
//   destination port and peer from the routing table; pin-compatible with
//   the fixed crossbar of dpe_switch.DUMMY.sv, top.filelist picks one
//==========================================================================

module dpe_switch
  import lkup_pkg::*;
(
    dpe_if.s_axis    inp,
    dpe_if.m_axis    out,
    // the CSR routing_table regfile (csr.rdl)
    input  csr_cfg_t csr_cfg,
    output csr_sta_t csr_sta
);
  egress_ip_lookup #(
      .ENTRY_COUNT (64)
  ) u_egress (
      .s_axis  (inp),
      .m_axis  (out),
      .csr_cfg (csr_cfg),
      .csr_sta (csr_sta)
  );
endmodule

